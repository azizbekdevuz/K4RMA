#if UNITY_EDITOR
using System;
using System.Collections.Generic;
using System.Reflection;
using KarmaPrototype;
using UnityEngine;

// Run synchronously in the main suite's initial geometry-check player-loop tick.
// This reproduces the red square through real damage, then restores every state
// touched by that path and removes only VFX created by these calls.
public static class KarmaHitFlashChecks
{
    const BindingFlags Private = BindingFlags.Instance | BindingFlags.NonPublic;
    static int assertions;
    static FieldInfo Field(object target, string name)
        => target.GetType().GetField(name, Private) ?? throw new Exception("Hit flash: missing field " + name);
    static T Get<T>(object target, string name) => (T)Field(target, name).GetValue(target);
    static void Set(object target, string name, object value) => Field(target, name).SetValue(target, value);
    static bool Near(float a, float b) => Mathf.Abs(a - b) < 0.0001f;
    static void Check(bool ok, string message)
    { assertions++; if (!ok) throw new Exception("Hit flash: " + message); }

    sealed class State
    {
        readonly object target;
        readonly Dictionary<FieldInfo, object> fields = new Dictionary<FieldInfo, object>();
        public State(object target, params string[] names)
        {
            this.target = target;
            foreach (string name in names)
            {
                var field = Field(target, name);
                fields.Add(field, field.GetValue(target));
            }
        }
        public void Restore()
        { foreach (var pair in fields) pair.Key.SetValue(target, pair.Value); }
    }

    static HashSet<Transform> Children(Transform root)
    {
        var children = new HashSet<Transform>();
        foreach (Transform child in root) children.Add(child);
        return children;
    }
    static List<Transform> NewChildren(Transform root, HashSet<Transform> original)
    {
        var children = new List<Transform>();
        foreach (Transform child in root) if (!original.Contains(child)) children.Add(child);
        return children;
    }
    static List<SpriteRenderer> HitFlashes(Transform root, HashSet<Transform> original)
    {
        var flashes = new List<SpriteRenderer>();
        foreach (var child in NewChildren(root, original))
        {
            var sprite = child.GetComponent<SpriteRenderer>();
            if (child.name == "Effect" && sprite != null && sprite.sprite != null
                && sprite.sprite.texture.name == "K4RMA_RuntimePixel") flashes.Add(sprite);
        }
        return flashes;
    }

    public static int Run(KarmaGame game)
    {
        assertions = 0;
        Check(game != null && game.World != null && game.Player != null && game.IsCombat,
            "probe runs in an active unpaused fight");
        var player = game.Player;
        Check(player.Health > 1, "nonlethal damage cannot invoke defeat or combat cleanup");
        var animator = Get<KarmaCharacterAnimator>(player, "animator");
        var techniques = Get<KarmaTechniqueState>(player, "techniques");
        var motion = Get<KarmaAirSlashMotion>(player, "airSlashMotion");
        var hits = Get<HashSet<KarmaEnemy>>(player, "airSlashHits");
        var savedHits = new List<KarmaEnemy>(hits);
        var savedPlayer = new State(player, "<Health>k__BackingField", "invulnerableUntil", "guardUntil",
            "airSlashRunning", "airSlashBufferedUntil", "airRecoveryLeft");
        var savedMotion = new State(motion, "elapsed", "duration");
        var savedCounter = new State(techniques, "counterArmed");
        var savedAnimator = new State(animator, "hurtUntil");
        float health = player.Health, damageTaken = game.DamageTaken;
        var random = UnityEngine.Random.state;
        var original = Children(game.World);
        try
        {
            // The counter branch damages enemies and spawns projectiles; exclude
            // it without consuming or changing the caller's saved counter state.
            Set(techniques, "counterArmed", false);
            Set(player, "invulnerableUntil", float.NegativeInfinity);
            Set(player, "guardUntil", float.NegativeInfinity);
            player.TakeDamage(1);
            Check(Near(player.Health, health - 1) && Near(game.DamageTaken, damageTaken + 1),
                "the red square is generated by real nonlethal player damage");
            var flashes = HitFlashes(game.World, original);
            Check(flashes.Count == 1, "one valid hit creates one named RuntimePixel Effect");
            var flash = flashes[0];
            Check(flash.sprite.texture.width == 1 && flash.sprite.texture.height == 1
                && flash.sprite.rect.size == Vector2.one,
                "the square comes from the explicit white runtime pixel rather than a PNG background");
            Check(flash.color == new Color(1, 0.2f, 0.3f, 1) && flash.sortingOrder == 10,
                "the existing red-pink hit-feedback tint and sorting order remain intact");
            Check(flash.transform.position == player.transform.position
                && flash.transform.localScale == new Vector3(KarmaSpace.Scale, KarmaSpace.Scale, 1),
                "the hit flash is centered on the player at the existing square size");
            Check(flash.GetComponent<Collider2D>() == null && flash.GetComponent<KarmaBossAttack>() == null,
                "the visible square owns no collider or boss attack damage");
            var effect = flash.GetComponent<KarmaEffect>();
            Check(effect != null && Near(Get<float>(effect, "duration"), 0.18f)
                && Near(Get<float>(effect, "left"), 0.18f) && Near(Get<float>(effect, "initialAlpha"), 1),
                "the normal hit flash retains its 0.18-second fading lifetime");
            Set(effect, "left", 0.09f + Time.deltaTime);
            typeof(KarmaEffect).GetMethod("Update", Private).Invoke(effect, null);
            Check(Near(flash.color.a, 0.5f), "the normal hit-feedback square becomes translucent while fading");

            float afterHit = player.Health, afterDamage = game.DamageTaken;
            var beforeImmune = Children(game.World);
            Set(player, "invulnerableUntil", Time.time + 10);
            player.TakeDamage(1);
            Check(player.Health == afterHit && game.DamageTaken == afterDamage
                && NewChildren(game.World, beforeImmune).Count == 0,
                "an invulnerable player takes no damage and produces no extra hit flash");

            Set(player, "invulnerableUntil", float.NegativeInfinity);
            Set(player, "guardUntil", Time.time + 10);
            var beforeShield = Children(game.World);
            player.TakeDamage(1);
            Check(player.Health == afterHit && game.DamageTaken == afterDamage
                && HitFlashes(game.World, beforeShield).Count == 0,
                "a shielded player takes no damage and produces no red hit flash");
            var shieldEffects = NewChildren(game.World, beforeShield);
            Check(shieldEffects.Count == 1 && shieldEffects[0].name == "PlayerVFX/Barrier"
                && shieldEffects[0].GetComponent<KarmaCombatVFX>() != null,
                "the existing shield-impact visual remains present instead");
            return assertions;
        }
        finally
        {
            savedPlayer.Restore(); savedMotion.Restore(); savedCounter.Restore(); savedAnimator.Restore();
            hits.Clear(); foreach (var enemy in savedHits) hits.Add(enemy);
            game.DamageTaken = damageTaken;
            UnityEngine.Random.state = random;
            foreach (var child in NewChildren(game.World, original))
                if (child != null) UnityEngine.Object.DestroyImmediate(child.gameObject);
        }
    }
}
#endif
